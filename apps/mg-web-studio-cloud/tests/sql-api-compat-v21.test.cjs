"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const root=path.join(__dirname,".."),read=p=>fs.readFileSync(path.join(root,p),"utf8");
const window={};new Function("window",read("shared/mg-sql-api-compat-v21.js"))(window);
const v=window.MGSqlApiCompatV21;
let count=0;function check(condition,label){assert.ok(condition,label);count++;}
const inputs={core:read("db/schema_core.review.sql"),proposals:read("db/v13-propuestas-scopes.review.sql"),api:read("shared/mg-contracts-v20.js")};
const report=v.audit(inputs);
check(report.version==="21.0-review","V21 version");
check(report.mode==="static-no-execution","Read-only mode");
check(report.go===false,"No GO");
check(report.sqlExecuted===false,"No SQL");
check(report.productionReady===false,"Not production ready");
check(report.pages.tableFound,"Pages table");
check(report.pages.nonEmptySlug,"Nonempty slug");
check(report.pages.slugRegexAcceptsHome,"Home allowed");
check(report.pages.uniqueSiteSlug,"Unique slug");
check(report.canonicalStates.length===6,"Canonical states");
check(report.sqlStates.includes("submitted_for_review"),"Old submitted");
check(report.sqlStates.includes("applied_to_draft"),"Old applied");
check(!report.sqlStates.includes("submitted"),"SQL not silently migrated");
check(report.apiStates.length===6,"V20 contract recognized");
for(const [key,value] of Object.entries(v.LEGACY))check(report.legacyReadAliases[key]===value,"Read alias "+key);
for(const code of ["STATUS_CONTRACT_MISMATCH","HOME_EXISTENCE_UNPROVEN","SECURITY_DEFINER_REVIEW","CAS_SQL_TRANSACTION_UNPROVEN","POSTGRES_REQUIRED"])check(report.issues.some(x=>x.code===code),"Blocker "+code);
const missing=v.audit({...inputs,proposals:""});check(missing.issues.some(x=>x.code==="SQL_STATUS_UNREADABLE"),"Reject missing CHECK");
const missingHome=v.audit({...inputs,core:""});check(missingHome.issues.some(x=>x.code==="HOME_SCHEMA_REVIEW"),"Reject missing Home schema");
const removedApi=v.audit({...inputs,api:""});check(removedApi.issues.some(x=>x.code==="API_CONTRACT_UNVERIFIED"),"Reject missing API contract");
check(!/fetch\s*\(|supabase\s*\.|execute\s*\(/i.test(read("shared/mg-sql-api-compat-v21.js")),"No network/database");
console.log(count+" / "+count+" V21 static compatibility checks passed; NO GO remains.");
